class TestYaraScanOverTheSharedFolder:
    """``yara_scan`` reads real artifacts under the host side of the shared folder."""

    def test_a_scan_without_a_share_is_refused(self) -> None:
        """A sandbox with no shared folder cannot be scanned."""
        with pytest.raises(SandboxError, match="Shared folder not initialized"):
            asyncio.run(_HostBoundSandbox().yara_scan())

    def test_a_rules_file_replaces_the_built_in_rules(self, tmp_path: Path) -> None:
        """Rules read from ``rules_path`` decide the matches, not the built-in set.

        Args:
            tmp_path: Pytest temporary directory.
        """
        share = _share_with_output(tmp_path)
        sandbox = _HostBoundSandbox()
        sandbox.bind(share, running=True)
        artifact = share / "output" / "collected.bin"
        artifact.write_bytes(_INJECTOR_STRINGS + _CUSTOM_RULE_MARKER)
        rules = tmp_path / "custom.yar"
        rules.write_text(_CUSTOM_RULES, encoding="utf-8")

        matches = asyncio.run(sandbox.yara_scan(rules_path=str(rules)))

        assert {match["rule"] for match in matches} == {"CustomMarker"}
        assert {match["source"] for match in matches} == {str(artifact)}

    def test_dropped_file_archives_are_unpacked_and_their_members_scanned(self, tmp_path: Path) -> None:
        """Every ``dropped_files_*.zip`` is extracted and its files are the scan inputs.

        Args:
            tmp_path: Pytest temporary directory.
        """
        share = _share_with_output(tmp_path)
        output_dir = share / "output"
        sandbox = _HostBoundSandbox()
        sandbox.bind(share, running=True)
        for archive_name, member_name in (("dropped_files_aa.zip", "first.bin"), ("dropped_files_bb.zip", "second.bin")):
            with zipfile.ZipFile(output_dir / archive_name, "w") as archive:
                archive.writestr(f"Downloads/{member_name}", _INJECTOR_STRINGS)

        matches = asyncio.run(sandbox.yara_scan())

        sources = [Path(match["source"]) for match in matches]
        assert {match["rule"] for match in matches} == {"SuspiciousStrings"}
        assert sorted(source.name for source in sources) == ["first.bin", "second.bin"]
        for source in sources:
            extraction_dir = source.parent.parent
            assert extraction_dir.parent == output_dir
            assert extraction_dir.name.startswith("yara_scan_")
            assert source.parent.name == "Downloads"


