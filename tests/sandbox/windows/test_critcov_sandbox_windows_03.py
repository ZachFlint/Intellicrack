class _HostBoundSandbox(WindowsSandbox):
    """A ``WindowsSandbox`` bound to directories on this host, with no guest launched.

    Only what a live sandbox would supply is arranged: where the shared folder
    is, and whether the sandbox counts as running. Every method under test is
    the production one; the wrappers exist so tests can reach protected
    members without touching them from outside the class.
    """

    def __init__(self, config: SandboxConfig | None = None) -> None:
        """Create the sandbox with a bounded command budget.

        Args:
            config: Optional sandbox configuration; a short command timeout is
                used when omitted so a broken guest cannot stall a test.
        """
        super().__init__(config or SandboxConfig(timeout_seconds=_COMMAND_BUDGET_SECONDS))

    def bind(self, shared: Path, *, running: bool) -> None:
        """Point the sandbox at a host directory and set its running state.

        Args:
            shared: Directory standing in for the guest's shared folder.
            running: Whether the sandbox should report ``running``.
        """
        self.SANDBOX_SHARED_PATH = str(shared)
        self._shared_folder = shared
        self.state.status = "running" if running else "stopped"

    def mark_running(self) -> None:
        """Set the sandbox status to ``running`` without a shared folder."""
        self.state.status = "running"

    def dispatcher_source(self) -> str:
        """Return the in-guest dispatcher PowerShell the sandbox would stage.

        Returns:
            str: The generated dispatcher script source.
        """
        return self._dispatcher_ps1_source()

    def shared_folder(self) -> Path:
        """Return the host directory bound as the shared folder.

        Returns:
            Path: The bound shared folder.
        """
        assert self._shared_folder is not None
        return self._shared_folder

    def ready_flag_path(self) -> Path:
        """Return the flag file the dispatcher writes when it comes up.

        Returns:
            Path: Host path of the readiness flag.
        """
        return self.shared_folder() / "flags" / self.DISPATCHER_READY_MARKER

    async def query_wmi_identity(self) -> dict[str, str]:
        """Run the production WMI identity query through the guest channel.

        Returns:
            dict[str, str]: The identity values the guest reported.
        """
        return await self._query_wmi_identity()

    async def apply_wmi_hijack(self, machine_name: str) -> dict[str, object]:
        """Run the production WMI hijack step for the default profile.

        Args:
            machine_name: Computer name to inject.

        Returns:
            dict[str, object]: Result mapping from the hijack step.
        """
        return await self._apply_wmi_hijack(resolve_anti_evasion_profile("default"), machine_name)

    async def minidump(self, pid: int, dump_path: Path) -> bool:
        """Run the production host-side minidump with its procdump fallback.

        Args:
            pid: Process to dump.
            dump_path: Destination dump path.

        Returns:
            bool: Whether a dump file was produced.
        """
        return await self._minidump_via_procdump(pid, dump_path)


def _copy_cmd_into(directory: Path) -> None:
    """Place a copy of the host ``cmd.exe`` in ``directory``.

    Args:
        directory: Directory that will be the only entry on a guest ``PATH``.

    Raises:
        AssertionError: If ``cmd.exe`` cannot be found on the host.
    """
    cmd = shutil.which("cmd.exe")
    if cmd is None:
        message = "cmd.exe is required to run the guest dispatcher"
        raise AssertionError(message)
    shutil.copy2(cmd, directory / "cmd.exe")


@contextlib.contextmanager
def _dispatcher_running(root: Path, *, tools_on_path: bool) -> Generator[_HostBoundSandbox]:
    """Run the real dispatcher script against a temporary shared folder.

    Args:
        root: Scratch directory for the share and the dispatcher script.
        tools_on_path: When true the dispatcher keeps the host ``PATH``; when
            false its ``PATH`` holds only a copy of ``cmd.exe``, so commands
            that need ``powershell``, ``xcopy`` or ``mofcomp`` are not found.

    Yields:
        _HostBoundSandbox: A running sandbox whose dispatcher is polling.
    """
    powershell = shutil.which(_POWERSHELL)
    assert powershell is not None, "this test needs the real powershell.exe to run the dispatcher"

    share = root / "IntellicrackShared"
    share.mkdir()
    sandbox = _HostBoundSandbox()
    sandbox.bind(share, running=True)

    environment = dict(os.environ)
    if not tools_on_path:
        guest_bin = root / "guest_bin"
        guest_bin.mkdir()
        _copy_cmd_into(guest_bin)
        environment["PATH"] = str(guest_bin)

    script = root / "dispatcher.ps1"
    script.write_text(sandbox.dispatcher_source(), encoding="utf-8")
    process = subprocess.Popen(
        [powershell, "-NoProfile", "-NonInteractive", "-ExecutionPolicy", "Bypass", "-File", str(script)],
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
        env=environment,
    )
    try:
        deadline = time.monotonic() + _DISPATCHER_READY_TIMEOUT
        while time.monotonic() < deadline and not sandbox.ready_flag_path().is_file():
            if process.poll() is not None:
                pytest.fail("the dispatcher exited before signalling ready")
            time.sleep(_DISPATCHER_POLL_SECONDS)
        assert sandbox.ready_flag_path().is_file(), "the real dispatcher never signalled ready"
        yield sandbox
    finally:
        process.terminate()
        try:
            process.wait(timeout=_DISPATCHER_READY_TIMEOUT)
        except subprocess.TimeoutExpired:
            process.kill()
            process.wait(timeout=_DISPATCHER_READY_TIMEOUT)


@pytest.fixture
def guest_without_tools(tmp_path: Path) -> Iterator[_HostBoundSandbox]:
    """Provide a dispatcher whose guest has no ``powershell``, ``xcopy`` or ``mofcomp``.

    Args:
        tmp_path: Directory for the shared folder and dispatcher script.

    Yields:
        _HostBoundSandbox: A running sandbox bound to the dispatcher.
    """
    with _dispatcher_running(tmp_path, tools_on_path=False) as sandbox:
        yield sandbox


@pytest.fixture
def guest_with_host_tools(tmp_path: Path) -> Iterator[_HostBoundSandbox]:
    """Provide a dispatcher whose guest sees the host ``PATH``.

    Args:
        tmp_path: Directory for the shared folder and dispatcher script.

    Yields:
        _HostBoundSandbox: A running sandbox bound to the dispatcher.
    """
    with _dispatcher_running(tmp_path, tools_on_path=True) as sandbox:
        yield sandbox


@pytest.fixture
def idle_child() -> Iterator[subprocess.Popen[str]]:
    """Spawn a Python child that prints a ready marker and then blocks on stdin.

    Yields:
        subprocess.Popen[str]: The running child process.
    """
    child = subprocess.Popen(
        [sys.executable, "-c", _CHILD_SCRIPT],
        stdin=subprocess.PIPE,
        stdout=subprocess.PIPE,
        stderr=subprocess.DEVNULL,
        text=True,
    )
    try:
        assert child.stdout is not None
        assert child.stdout.readline().strip() == _CHILD_READY_MARKER
        yield child
    finally:
        child.kill()
        child.communicate(timeout=_CHILD_STOP_TIMEOUT)


def _running_sandbox_without_share() -> _HostBoundSandbox:
    """Build a sandbox that is running but has no shared folder.

    Returns:
        _HostBoundSandbox: A sandbox in the running state with no share.
    """
    sandbox = _HostBoundSandbox()
    sandbox.mark_running()
    return sandbox


def _share_with_output(root: Path) -> Path:
    """Create a shared folder holding an ``output`` directory.

    Args:
        root: Parent directory.

    Returns:
        Path: The shared folder.
    """
    share = root / "share"
    (share / "output").mkdir(parents=True)
    return share


