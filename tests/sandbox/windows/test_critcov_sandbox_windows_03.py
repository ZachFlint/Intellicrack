"""Coverage for the Windows Sandbox backend paths that need no running sandbox.

Windows Sandbox cannot start in the test container, so nothing here launches
one. The guards that refuse work without a running sandbox or a shared folder
are driven directly. The host-side YARA scan reads real files in a temporary
shared folder. The host-side minidump helpers dump a real child process the
test spawns. The guest command channel is exercised with the production
dispatcher script, generated by the sandbox with its shared path pointed at a
temporary directory and run under the real ``powershell.exe``; one guest has
only a copy of ``cmd.exe`` on its ``PATH`` so the guest tools a real sandbox
provides (``powershell``, ``xcopy``, ``mofcomp``) are absent, and the other
keeps the host ``PATH``.
"""

