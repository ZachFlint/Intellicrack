_POWERSHELL: Final[str] = "powershell.exe"
_DISPATCHER_READY_TIMEOUT: Final[float] = 90.0
_DISPATCHER_POLL_SECONDS: Final[float] = 0.25
_COMMAND_BUDGET_SECONDS: Final[int] = 90
_STAGING_WAIT_SECONDS: Final[float] = 60.0
_STAGING_POLL_SECONDS: Final[float] = 0.02
_CHILD_READY_MARKER: Final[str] = "ready"
_CHILD_SCRIPT: Final[str] = "import sys\nprint('ready', flush=True)\nsys.stdin.read()\n"
_CHILD_STOP_TIMEOUT: Final[float] = 30.0
_NONEXISTENT_PID: Final[int] = 0xFFFFFFFC
_MINIDUMP_SIGNATURE: Final[bytes] = b"MDMP"
_INJECTOR_STRINGS: Final[bytes] = b"MZ\x90\x00" + b"\x00" * 16 + b"CreateRemoteThread\x00VirtualAllocEx\x00"
_CUSTOM_RULE_MARKER: Final[bytes] = b"critcov-marker-7f3a"
_CUSTOM_RULES: Final[str] = 'rule CustomMarker {\n    strings:\n        $m = "critcov-marker-7f3a"\n    condition:\n        $m\n}\n'

