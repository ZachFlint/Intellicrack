def _drop_file_if_staged(output_dir: Path, file_name: str, payload: bytes) -> Path | None:
    """Write a file into the extraction staging directory if it exists yet.

    Args:
        output_dir: The shared folder's ``output`` directory.
        file_name: Name of the file to create under a ``Downloads`` subfolder.
        payload: Bytes to write.

    Returns:
        Path | None: The staging directory written into, or None when none exists yet.
    """
    staging = [entry for entry in output_dir.glob("dropped_*") if entry.is_dir()]
    if not staging:
        return None
    target_dir = staging[0] / "Downloads"
    target_dir.mkdir(parents=True, exist_ok=True)
    (target_dir / file_name).write_bytes(payload)
    return staging[0]


async def _drop_file_into_staging(output_dir: Path, file_name: str, payload: bytes) -> Path:
    """Write a file into the extraction staging directory as soon as it appears.

    Args:
        output_dir: The shared folder's ``output`` directory.
        file_name: Name of the file to create under a ``Downloads`` subfolder.
        payload: Bytes to write.

    Returns:
        Path: The staging directory the file was written into.

    Raises:
        AssertionError: If no staging directory appears in time.
    """
    deadline = time.monotonic() + _STAGING_WAIT_SECONDS
    while time.monotonic() < deadline:
        staged = await asyncio.to_thread(_drop_file_if_staged, output_dir, file_name, payload)
        if staged is not None:
            return staged
        await asyncio.sleep(_STAGING_POLL_SECONDS)
    message = "the extraction never created a staging directory"
    raise AssertionError(message)
