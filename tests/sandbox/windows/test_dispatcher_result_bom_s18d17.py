r"""Gate for S18-D17: a Windows Sandbox run must report the exit code it actually got.

Driven live on 2026-08-15: a target that ran to completion and printed its final line came
back as ``exit_code=-2, result=error``. The in-guest dispatcher publishes the code with
``Set-Content -LiteralPath $res -Value ([string]$code) -Encoding utf8``, and under Windows
PowerShell 5.1 ``-Encoding utf8`` writes UTF-8 **with a BOM**. The host decoded that file as
plain ``utf-8``, so the code arrived carrying a leading U+FEFF; ``str.strip()`` left it
there - U+FEFF is not whitespace - ``isdigit()`` said no, and the reader fell through to
``_RETURNCODE_UNKNOWN``. Every Windows Sandbox execution was a false red.

Nothing here restates what the guest writes. The gate runs **the real dispatcher script**,
generated by the production ``_dispatcher_ps1_source`` with its shared path pointed at a
temporary directory, under the real ``powershell.exe``; the host side is the production
``run_command``. So the bytes under test are produced by the same statement the guest runs,
and both halves of the boundary are the shipped ones.

The BOM is asserted directly, on the ready flag - written by that same
``Set-Content -Encoding utf8`` and, unlike the per-ticket result file, not deleted - so this
gate cannot pass vacuously on a host whose PowerShell writes something else.
"""

from __future__ import annotations

import asyncio
import codecs
import contextlib
import re
import shutil
import subprocess
import sys
import time
from typing import TYPE_CHECKING, Final

import pytest

from intellicrack.sandbox.windows import WindowsSandbox


if TYPE_CHECKING:
    from collections.abc import Iterator
    from pathlib import Path


_PRODUCER_RE: Final[re.Pattern[str]] = re.compile(
    r"Set-Content -LiteralPath \$res -Value \(\[string\]\$code\) -Encoding utf8",
)
_POWERSHELL: Final[str] = "powershell.exe"
_DISPATCHER_READY_TIMEOUT: Final[float] = 90.0
_DISPATCHER_POLL_SECONDS: Final[float] = 0.25
_COMMAND_TIME_LIMIT: Final[int] = 60

pytestmark = pytest.mark.skipif(sys.platform != "win32", reason="Windows Sandbox is a Windows backend")


class _DispatcherSandbox(WindowsSandbox):
    """A ``WindowsSandbox`` whose shared path is a directory on this host.

    Only the two things a live sandbox would supply are arranged - where the
    share is, and that the sandbox is running. The dispatcher script, the
    trigger write, the polling and the result read are all production code.
    """

    def use_shared_folder(self, folder: Path) -> None:
        """Point both sides of the dispatcher at a host directory.

        Args:
            folder: Directory standing in for the mounted shared folder.
        """
        self.SANDBOX_SHARED_PATH = str(folder)
        self._shared_folder = folder
        self.state.status = "running"

    def dispatcher_source(self) -> str:
        """Return the in-guest dispatcher PowerShell the sandbox would stage.

        Returns:
            str: The generated dispatcher script source.
        """
        return self._dispatcher_ps1_source()

    def ready_flag_path(self) -> Path:
        """Return the flag file the dispatcher writes when it comes up.

        Returns:
            Path: Host path of the readiness flag.
        """
        assert self._shared_folder is not None
        return self._shared_folder / "flags" / self.DISPATCHER_READY_MARKER


@pytest.fixture
def dispatcher(tmp_path: Path) -> Iterator[_DispatcherSandbox]:
    """Run the real dispatcher script against a temporary shared folder.

    Args:
        tmp_path: Directory standing in for the mounted shared folder.

    Yields:
        _DispatcherSandbox: A sandbox whose dispatcher is up and polling.
    """
    powershell = shutil.which(_POWERSHELL)
    assert powershell is not None, "this gate needs the real powershell.exe to run the dispatcher"

    share = tmp_path / "IntellicrackShared"
    share.mkdir()
    sandbox = _DispatcherSandbox()
    sandbox.use_shared_folder(share)

    script = tmp_path / "dispatcher.ps1"
    script.write_text(sandbox.dispatcher_source(), encoding="utf-8")
    process = subprocess.Popen(
        [powershell, "-NoProfile", "-NonInteractive", "-ExecutionPolicy", "Bypass", "-File", str(script)],
        stdout=subprocess.DEVNULL,
        stderr=subprocess.PIPE,
        text=True,
    )
    try:
        deadline = time.monotonic() + _DISPATCHER_READY_TIMEOUT
        while time.monotonic() < deadline and not sandbox.ready_flag_path().is_file():
            if process.poll() is not None:
                pytest.fail(f"the dispatcher exited before signalling ready: {process.communicate()[1]}")
            time.sleep(_DISPATCHER_POLL_SECONDS)
        assert sandbox.ready_flag_path().is_file(), "the real dispatcher never signalled ready"
        yield sandbox
    finally:
        process.terminate()
        with contextlib.suppress(subprocess.TimeoutExpired):
            process.wait(timeout=_DISPATCHER_READY_TIMEOUT)


class TestTheCodeCrossesTheDispatcherIntact:
    """What the dispatcher published is what ``run_command`` must return."""

    def test_the_producer_is_still_what_the_dispatcher_uses(self, dispatcher: _DispatcherSandbox) -> None:
        """The statement whose encoding this gate turns on is the one the source carries.

        Args:
            dispatcher: The running dispatcher under test.
        """
        assert _PRODUCER_RE.search(dispatcher.dispatcher_source()) is not None, (
            "the dispatcher no longer publishes the exit code with -Encoding utf8, so what "
            "this gate exercises is no longer what the guest does and it must be re-aimed"
        )

    def test_the_dispatcher_really_writes_a_bom(self, dispatcher: _DispatcherSandbox) -> None:
        """The bytes that PowerShell wrote open with a BOM, or this gate proves nothing.

        Args:
            dispatcher: The running dispatcher under test.
        """
        assert dispatcher.ready_flag_path().read_bytes().startswith(codecs.BOM_UTF8), (
            "this PowerShell did not emit a BOM, so a reader that mishandles one would still pass every assertion below"
        )

    @pytest.mark.parametrize("code", [0, 1, 3, 42])
    def test_run_command_returns_the_real_exit_code(self, dispatcher: _DispatcherSandbox, code: int) -> None:
        """A command that exits with a code is reported with that code.

        Args:
            dispatcher: The running dispatcher under test.
            code: Exit code the dispatched command produces.
        """
        exit_code, _, _ = asyncio.run(
            dispatcher.run_command(f"exit /b {code}", time_limit=_COMMAND_TIME_LIMIT),
        )
        assert exit_code == code, (
            f"the command exited {code} and the sandbox reported {exit_code}; a run that "
            "succeeded is indistinguishable from one that failed"
        )

    def test_output_still_comes_back_with_the_code(self, dispatcher: _DispatcherSandbox) -> None:
        """A successful command reports both its zero exit code and its output.

        Args:
            dispatcher: The running dispatcher under test.
        """
        exit_code, stdout, _ = asyncio.run(
            dispatcher.run_command("echo s18d17-marker", time_limit=_COMMAND_TIME_LIMIT),
        )
        assert exit_code == 0, f"a successful command reported {exit_code}"
        assert "s18d17-marker" in stdout, f"the command's output did not come back: {stdout!r}"
